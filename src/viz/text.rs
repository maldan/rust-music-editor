#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn title_and_credit_emit_quads() {
        let qs = overlay_quads("Song", "Author: Ada", 16.0 / 9.0);
        assert!(qs.len() > 20);
        assert!(qs.iter().all(|q| q.x < 0.6 && q.y < overlay_reserve("Song", "Author: Ada")));
        let title_h = qs.iter().filter(|q| q.y < 0.04).map(|q| q.y + q.h).fold(0.0f32, f32::max)
            - qs.iter().filter(|q| q.y < 0.04).map(|q| q.y).fold(f32::MAX, f32::min);
        assert!(title_h < 0.034, "title too tall {title_h}");
    }

    #[test]
    fn empty_overlay_is_empty() {
        assert!(overlay_quads("  ", "", 1.0).is_empty());
        assert_eq!(overlay_reserve("  ", ""), 0.0);
    }
}

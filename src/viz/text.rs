use super::layout::Quad;

const COLOR: [f32; 4] = [0.94, 0.94, 0.90, 0.92];
const Y0: f32 = 0.016;
const TITLE_H: f32 = 0.028;
const CREDIT_H: f32 = 0.016;
const GAP: f32 = 0.006;
const BELOW: f32 = 0.014;

/// Bottom of the title/credit block, plus a little air before notes.
pub fn overlay_reserve(title: &str, credit: &str) -> f32 {
    let mut y = Y0;
    let has_title = !title.trim().is_empty();
    let has_credit = !credit.trim().is_empty();
    if has_title {
        y += TITLE_H;
    }
    if has_title && has_credit {
        y += GAP;
    }
    if has_credit {
        y += CREDIT_H;
    }
    if has_title || has_credit {
        y + BELOW
    } else {
        0.0
    }
}

pub fn overlay_quads(title: &str, credit: &str, aspect: f32) -> Vec<Quad> {
    let aspect = aspect.max(0.1);
    let mut out = Vec::new();
    let mut y = Y0;
    if !title.trim().is_empty() {
        draw_line(&mut out, title.trim(), 0.022, y, TITLE_H, aspect);
        y += TITLE_H + GAP;
    }
    if !credit.trim().is_empty() {
        draw_line(&mut out, credit.trim(), 0.022, y, CREDIT_H, aspect);
    }
    out
}

fn draw_line(out: &mut Vec<Quad>, text: &str, x0: f32, y0: f32, h: f32, aspect: f32) {
    let px = h / 7.0;
    let dx = px / aspect;
    let mut x = x0;
    for ch in text.chars() {
        if x > 0.98 {
            break;
        }
        if let Some(rows) = glyph(ch) {
            for (row, bits) in rows.iter().enumerate() {
                for col in 0..5 {
                    if bits & (1 << (4 - col)) != 0 {
                        out.push(Quad {
                            x: x + col as f32 * dx,
                            y: y0 + row as f32 * px,
                            w: dx * 1.05,
                            h: px * 1.05,
                            color: COLOR,
                            round: 0.0,
                            glow: 0.0,
                            stroke: 0.0,
                        });
                    }
                }
            }
        }
        x += dx * 6.0;
    }
}

